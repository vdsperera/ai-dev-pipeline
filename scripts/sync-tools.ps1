<#
.SYNOPSIS
    Cross-Tool Rules & Instructions Synchronizer (PowerShell)
.DESCRIPTION
    Synchronizes the AI Dev Pipeline's central coding standards (.agents/AGENTS.md)
    into native configuration files for other AI coding environments:
      - Claude Code: generates CLAUDE.md
      - Cursor: generates .cursorrules and .cursor/rules/agents.mdc
.EXAMPLE
    .\scripts\sync-tools.ps1
    .\scripts\sync-tools.ps1 -Target Claude
    .\scripts\sync-tools.ps1 -Target Cursor
    .\scripts\sync-tools.ps1 -Check
#>

param(
    [ValidateSet("All", "Claude", "Cursor")]
    [string]$Target = "All",
    [switch]$Check
)

$ErrorActionPreference = "Stop"
$rootDir = Resolve-Path (Join-Path $PSScriptRoot "..")
$agentsMdPath = Join-Path $rootDir ".agents\AGENTS.md"

if (-not (Test-Path $agentsMdPath)) {
    Write-Error "Required file not found: $agentsMdPath"
    exit 1
}

$agentsContent = Get-Content -Path $agentsMdPath -Raw -Encoding UTF8

# Generate CLAUDE.md
$claudeContent = @"
<!-- Generated by scripts/sync-tools.ps1. Do not edit directly. -->
# CLAUDE.md — AI Dev Pipeline Configuration

> This project uses the **AI Dev Pipeline** with 17 specialized agent personas and 16 skills.
> When working in this codebase with Claude Code, strictly follow the baseline coding standards, quality gates, and anti-pattern rules below.

