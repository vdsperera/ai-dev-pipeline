## Baseline Coding Standards & Invariants

$($agentsContent -replace "(?m)^# AI Dev Pipeline — Coding Standards\s*\r?\n?", "")
"@

# Generate .cursorrules
$cursorRulesContent = @"
<!-- Generated by scripts/sync-tools.ps1. Do not edit directly. -->
# Cursor Rules — AI Dev Pipeline

You are working inside a codebase governed by the AI Dev Pipeline. Enforce the following standards on every interaction:

$agentsContent
"@

# Generate .cursor/rules/agents.mdc
$cursorMdcContent = @"
---
description: Always-on coding standards, quality gates, and anti-pattern invariants for AI Dev Pipeline
globs: *
alwaysApply: true
---

<!-- Generated by scripts/sync-tools.ps1. Do not edit directly. -->
$agentsContent
"@

$updated = @()
$outOfSync = @()

function Write-Or-Check {
    param(
        [string]$Path,
        [string]$Content
    )

    $parentDir = Split-Path -Parent $Path
    if (-not (Test-Path $parentDir)) {
        New-Item -ItemType Directory -Path $parentDir -Force | Out-Null
    }

    if ($Check) {
        if (-not (Test-Path $Path)) {
            $script:outOfSync += $Path
        } else {
            $existing = Get-Content -Path $Path -Raw -Encoding UTF8
            if ($existing.Trim() -ne $Content.Trim()) {
                $script:outOfSync += $Path
            }
        }
    } else {
        [System.IO.File]::WriteAllText($Path, $Content, [System.Text.Encoding]::UTF8)
        $script:updated += $Path
    }
}

Write-Host "[sync-tools] Synchronizing cross-tool configurations..." -ForegroundColor Cyan

if ($Target -eq "All" -or $Target -eq "Claude") {
    Write-Or-Check -Path (Join-Path $rootDir "CLAUDE.md") -Content $claudeContent
}

if ($Target -eq "All" -or $Target -eq "Cursor") {
    Write-Or-Check -Path (Join-Path $rootDir ".cursorrules") -Content $cursorRulesContent
    Write-Or-Check -Path (Join-Path $rootDir ".cursor\rules\agents.mdc") -Content $cursorMdcContent
}

if ($Check) {
    if ($outOfSync.Count -gt 0) {
        Write-Error "[sync-tools] ERROR: The following tool configuration files are out of sync: `n$($outOfSync -join "`n")"
        exit 1
    } else {
        Write-Host "[sync-tools] SUCCESS: All cross-tool configuration files are up to date!" -ForegroundColor Green
    }
} else {
    Write-Host "[sync-tools] Successfully synchronized cross-tool configurations:" -ForegroundColor Green
    foreach ($file in $updated) {
        Write-Host "  + $(Resolve-Path -Relative $file)" -ForegroundColor Green
    }
    Write-Host "`nYour AI coding standards are now active across Antigravity, Cursor, and Claude Code." -ForegroundColor Cyan
}
