/**
 * tests/sync-tools.test.js — Unit Tests for Cross-Editor Skill & Rule Generators
 *
 * Uses Node.js native test runner (node:test). Zero external dependencies.
 */

'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const path = require('path');
const {
  getAvailableSkills,
  generateClaudeMd,
  generateClaudeSkillCommand,
  generateCursorRules,
  generateCursorMdc,
  generateCursorSkillMdc,
  generateCopilotInstructions,
  generateCopilotPrompt,
  runSynchronizer
} = require('../scripts/sync-tools');

const sampleSkill = {
  name: 'sdlc-develop',
  description: 'Implement a task following Agent 6 standards.',
  body: '## Workflow\nRead [`prompts/06-developer.md`](../../prompts/06-developer.md) and implement code.'
};

const sampleAgentsContent = '# AI Dev Pipeline — Coding Standards\n\n- All I/O operations are wrapped in error handling.';

test('getAvailableSkills discovers all 19 skills from .agents/skills/', () => {
  const skills = getAvailableSkills(path.join(__dirname, '..', '.agents', 'skills'));
  assert.equal(skills.length, 19);
  const names = skills.map(s => s.name);
  assert.ok(names.includes('sdlc-develop'));
  assert.ok(names.includes('sdlc-architect'));
  assert.ok(names.includes('sdlc-debug'));
  assert.ok(names.includes('sdlc-retro'));
  assert.ok(names.includes('sdlc-quick'));
  assert.ok(names.includes('sdlc-consult'));
  assert.ok(names.includes('pr-review'));
});

test('generateClaudeSkillCommand produces invocable Claude slash command', () => {
  const output = generateClaudeSkillCommand(sampleSkill);
  assert.match(output, /<!-- Generated by ai-dev-pipeline. Invocable in Claude Code as \/sdlc-develop -->/);
  assert.match(output, /# sdlc-develop/);
  assert.match(output, /Implement a task following Agent 6 standards\./);
  // Prompt paths should be normalized from ../../prompts/ to prompts/
  assert.match(output, /\(prompts\/06-developer\.md\)/);
  assert.doesNotMatch(output, /\(\.\.\/\.\.\/prompts\//);
});

test('generateCursorSkillMdc produces invocable Cursor MDC rule with alwaysApply: false', () => {
  const output = generateCursorSkillMdc(sampleSkill);
  assert.match(output, /alwaysApply: false/);
  assert.match(output, /description: Implement a task following Agent 6 standards\./);
  assert.match(output, /<!-- Generated by ai-dev-pipeline. Invocable in Cursor via @sdlc-develop -->/);
  assert.match(output, /\(prompts\/06-developer\.md\)/);
});

test('generateCopilotPrompt produces GitHub Copilot prompt file', () => {
  const output = generateCopilotPrompt(sampleSkill);
  assert.match(output, /description: Implement a task following Agent 6 standards\./);
  assert.match(output, /<!-- Generated by ai-dev-pipeline. Invocable in GitHub Copilot as \/sdlc-develop -->/);
  assert.match(output, /# sdlc-develop/);
});

test('generateCursorMdc produces always-on rule with alwaysApply: true', () => {
  const output = generateCursorMdc(sampleAgentsContent);
  assert.match(output, /alwaysApply: true/);
  assert.match(output, /All I\/O operations are wrapped in error handling/);
});

test('runSynchronizer in check mode verifies current repository files are up to date', () => {
  const ROOT_DIR = path.resolve(__dirname, '..');
  const results = runSynchronizer(['all'], ROOT_DIR, true);
  assert.equal(results.outOfSync.length, 0);
  assert.ok(results.upToDate.length >= 50);
});

test('runSynchronizer appends AGENTS.local.md when present in workspace', () => {
  const fs = require('fs');
  const tempDir = path.join(__dirname, 'temp-sync-test');
  fs.mkdirSync(path.join(tempDir, '.agents'), { recursive: true });
  fs.writeFileSync(path.join(tempDir, '.agents', 'AGENTS.md'), '# Base Rules', 'utf8');
  fs.writeFileSync(path.join(tempDir, 'AGENTS.local.md'), '- Must use UUIDv7 for IDs', 'utf8');

  const results = runSynchronizer(['cursor'], tempDir, false, path.join(__dirname, '..', '.agents', 'skills'));
  assert.ok(results.updated.length > 0);
  const cursorrules = fs.readFileSync(path.join(tempDir, '.cursorrules'), 'utf8');
  assert.match(cursorrules, /Project-Specific Rules \(AGENTS\.local\.md\)/);
  assert.match(cursorrules, /Must use UUIDv7 for IDs/);

  fs.rmSync(tempDir, { recursive: true, force: true });
});
